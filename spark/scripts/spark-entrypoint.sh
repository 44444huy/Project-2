#!/bin/sh
set -eu
: "${POLARIS_CLIENT_ID:?POLARIS_CLIENT_ID must be set}"
: "${POLARIS_CLIENT_SECRET:?POLARIS_CLIENT_SECRET must be set}"
: "${MINIO_ROOT_USER:?MINIO_ROOT_USER must be set}"
: "${MINIO_ROOT_PASSWORD:?MINIO_ROOT_PASSWORD must be set}"
SPARK_MASTER="${SPARK_MASTER:-local[2]}"
SPARK_DRIVER_MEMORY="${SPARK_DRIVER_MEMORY:-2g}"
SPARK_SHUFFLE_PARTITIONS="${SPARK_SHUFFLE_PARTITIONS:-8}"
SPARK_DEFAULT_PARALLELISM="${SPARK_DEFAULT_PARALLELISM:-8}"
SPARK_LOCAL_DIR="${SPARK_LOCAL_DIR:-/tmp/spark-local}"
export SPARK_MASTER SPARK_DRIVER_MEMORY SPARK_SHUFFLE_PARTITIONS
export SPARK_DEFAULT_PARALLELISM SPARK_LOCAL_DIR
mkdir -p /tmp/spark-conf "$SPARK_LOCAL_DIR"
envsubst '${POLARIS_CLIENT_ID} ${POLARIS_CLIENT_SECRET} ${MINIO_ROOT_USER} ${MINIO_ROOT_PASSWORD} ${SPARK_MASTER} ${SPARK_DRIVER_MEMORY} ${SPARK_SHUFFLE_PARTITIONS} ${SPARK_DEFAULT_PARALLELISM} ${SPARK_LOCAL_DIR}' \
  < /opt/project/spark-defaults.conf.template \
  > /tmp/spark-conf/spark-defaults.conf
export SPARK_CONF_DIR=/tmp/spark-conf
exec "$@"
